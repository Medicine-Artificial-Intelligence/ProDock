def convert_with_meeko(
    mekoo_cmd: str,
    input_pdb: Path,
    out_basename: Path,
    write_pdbqt: Optional[Path] = None,
    box_center: Optional[Tuple[float, float, float]] = None,
    box_size: Optional[Tuple[float, float, float]] = None,
    *,
    sanitize_rebuild: Optional[bool] = True,
    sanitize_aggressive: bool = False,
    sanitize_backup: bool = False,
) -> Dict[str, Any]:
    """
    Run a Meeko receptor-preparation command and collect produced artifacts.

    This helper calls ``mk_prepare_receptor.py`` (or a compatible wrapper) to
    generate receptor-preparation outputs. If a PDBQT file is produced, it is
    always sanitized in place.

    :param mekoo_cmd:
        Path or executable name for the Meeko receptor-preparation command.
    :type mekoo_cmd: str

    :param input_pdb:
        Input PDB file passed to Meeko.
    :type input_pdb: Path

    :param out_basename:
        Base output path used by Meeko for generated files, without the final
        extension.
    :type out_basename: Path

    :param write_pdbqt:
        Optional explicit path for a PDBQT output file.
    :type write_pdbqt: Optional[Path]

    :param box_center:
        Optional grid-box center as ``(x, y, z)``.
    :type box_center: Optional[Tuple[float, float, float]]

    :param box_size:
        Optional grid-box size as ``(sx, sy, sz)``.
    :type box_size: Optional[Tuple[float, float, float]]

    :param sanitize_rebuild:
        Whether sanitization should rebuild fixed-width ATOM/HETATM records.
    :type sanitize_rebuild: Optional[bool]

    :param sanitize_aggressive:
        Whether sanitization should use aggressive cleanup heuristics.
    :type sanitize_aggressive: bool

    :param sanitize_backup:
        Whether a backup should be created before in-place sanitization.
    :type sanitize_backup: bool

    :returns:
        Dictionary summarizing command execution. Keys include ``"called"``,
        ``"rc"``, ``"stdout"``, ``"stderr"``, and ``"produced"``.
    :rtype: Dict[str, Any]
    """
    exe = _resolve_executable(mekoo_cmd)

    info: Dict[str, Any] = {
        "called": None,
        "rc": None,
        "stdout": None,
        "stderr": None,
        "produced": [],
    }

    if not exe:
        info["stderr"] = f"Meeko command not found: {mekoo_cmd}"
        logger.warning(info["stderr"])
        return info

    input_pdb = _ensure_exists(input_pdb, "Input PDB")
    out_basename = Path(out_basename)
    if write_pdbqt is not None:
        write_pdbqt = Path(write_pdbqt)

    args: List[str] = [str(exe), "--read_pdb", str(input_pdb), "-o", str(out_basename)]

    if box_center is not None:
        args += [
            "--box_center",
            str(box_center[0]),
            str(box_center[1]),
            str(box_center[2]),
        ]

    if box_size is not None:
        args += [
            "--box_size",
            str(box_size[0]),
            str(box_size[1]),
            str(box_size[2]),
        ]

    if write_pdbqt is not None:
        args += ["--write_pdbqt", str(write_pdbqt)]

    info["called"] = " ".join(args)
    logger.debug("convert_with_mekoo: %s", info["called"])

    try:
        proc = subprocess.run(
            args,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
        )
        info["rc"] = proc.returncode
        info["stdout"] = proc.stdout
        info["stderr"] = proc.stderr
    except Exception as exc:
        info["rc"] = -1
        info["stderr"] = str(exc)
        logger.exception("convert_with_mekoo: invocation failed")
        return info

    produced: List[str] = []

    if write_pdbqt is not None and write_pdbqt.exists():
        _sanitize_pdbqt(
            write_pdbqt,
            backend="meeko",
            rebuild=sanitize_rebuild,
            aggressive=sanitize_aggressive,
            backup=sanitize_backup,
        )
        produced.append(str(write_pdbqt.resolve()))

    for ext in (".pdbqt", ".json"):
        cand = out_basename.with_suffix(ext)
        if cand.exists():
            if ext == ".pdbqt":
                _sanitize_pdbqt(
                    cand,
                    backend="meeko",
                    rebuild=sanitize_rebuild,
                    aggressive=sanitize_aggressive,
                    backup=sanitize_backup,
                )
            resolved = str(cand.resolve())
            if resolved not in produced:
                produced.append(resolved)

    info["produced"] = produced
    logger.debug("convert_with_mekoo: produced=%s", produced)
    return info


convert_with_mekoo = convert_with_meeko


def convert_with_obabel(
    input_path: Path,
    output_path: Path,
    extra_args: Optional[Sequence[str]] = None,
    *,
    sanitize_rebuild: Optional[bool] = False,
    sanitize_aggressive: bool = False,
    sanitize_backup: bool = False,
    validate_receptor: bool = False,
    flexibility: bool = False,
) -> None:
    """
    Convert a structure file with Open Babel and sanitize generated PDBQT output.

    Input and output formats are inferred from file extensions and passed to
    Open Babel using the canonical CLI form:

    .. code-block:: bash

        obabel -i<in_ext> input -o<out_ext> -O output

    When the output format is ``.pdbqt``, the generated file is sanitized in
    place. For receptor preparation, the helper can also validate whether the
    written PDBQT matches the requested rigid or flexible mode.

    :param input_path:
        Input structure file path.
    :type input_path: Path

    :param output_path:
        Output structure file path.
    :type output_path: Path

    :param extra_args:
        Optional extra CLI arguments forwarded to Open Babel.
    :type extra_args: Optional[Sequence[str]]

    :param sanitize_rebuild:
        Whether sanitization should rebuild fixed-width ATOM/HETATM records.
    :type sanitize_rebuild: Optional[bool]

    :param sanitize_aggressive:
        Whether sanitization should use aggressive cleanup heuristics.
    :type sanitize_aggressive: bool

    :param sanitize_backup:
        Whether a backup should be created before in-place sanitization.
    :type sanitize_backup: bool

    :param validate_receptor:
        Whether to validate the generated PDBQT as receptor output.
    :type validate_receptor: bool

    :param flexibility:
        Whether receptor PDBQT output should be generated in flexible mode.
    :type flexibility: bool

    :returns:
        This function returns nothing.
    :rtype: None

    :raises RuntimeError:
        If Open Babel is unavailable, conversion fails, output is missing, or
        receptor validation fails.

    :raises ValueError:
        If the input or output file extension is missing.
    """
    input_path = _ensure_exists(input_path, "Input file")
    output_path = Path(output_path)

    in_ext = input_path.suffix.lower().lstrip(".")
    out_ext = output_path.suffix.lower().lstrip(".")

    if not in_ext:
        raise ValueError(f"Input path has no extension: {input_path}")
    if not out_ext:
        raise ValueError(f"Output path has no extension: {output_path}")

    exe = shutil.which("obabel") or shutil.which("babel")
    if not exe:
        raise RuntimeError("Open Babel (obabel/babel) not found in PATH")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    user_extra_args = list(extra_args or [])

    if out_ext == "pdbqt" and validate_receptor:
        has_x_flag = any(
            isinstance(arg, str) and arg.startswith("-x") for arg in user_extra_args
        )
        if not has_x_flag:
            user_extra_args.append("-xs" if flexibility else "-xrc")

    args = [
        exe,
        f"-i{in_ext}",
        str(input_path),
        f"-o{out_ext}",
        "-O",
        str(output_path),
    ]
    args += user_extra_args

    logger.debug("convert_with_obabel: %s", " ".join(args))
    proc = subprocess.run(
        args,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )

    if proc.returncode != 0:
        logger.error(
            "convert_with_obabel: failed rc=%s stderr=%s",
            proc.returncode,
            proc.stderr,
        )
        raise RuntimeError(f"Open Babel conversion failed: {proc.stderr.strip()}")

    if not output_path.exists():
        raise RuntimeError("Open Babel reported success but output file is missing")

    if output_path.suffix.lower() == ".pdbqt":
        _sanitize_pdbqt(
            output_path,
            backend="obabel",
            rebuild=sanitize_rebuild,
            aggressive=sanitize_aggressive,
            backup=sanitize_backup,
        )

        if validate_receptor:
            _validate_receptor_pdbqt(output_path, flexible=flexibility)

    logger.info("convert_with_obabel: success -> %s", output_path)


