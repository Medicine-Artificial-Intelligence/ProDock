def _meeko_pdb_to_pdbqt(
    input_pdb: Path,
    output_pdbqt: Path,
    *,
    mode: Mode,
    extra_args: Optional[Sequence[str]] = None,
    meeko_cmd: Optional[str] = None,
    sanitize_rebuild: Optional[bool] = None,
    sanitize_aggressive: bool = False,
    sanitize_backup: bool = False,
) -> Path:
    """
    Convert PDB to PDBQT using Meeko.

    :param input_pdb:
        Input PDB path.
    :type input_pdb: Path

    :param output_pdbqt:
        Output PDBQT path.
    :type output_pdbqt: Path

    :param mode:
        Conversion mode.
    :type mode: Literal["receptor", "ligand"]

    :param extra_args:
        Optional extra CLI arguments.
    :type extra_args: Optional[Sequence[str]]

    :param meeko_cmd:
        Optional executable override.
    :type meeko_cmd: Optional[str]

    :param sanitize_rebuild:
        Whether sanitization should rebuild fixed-width ATOM/HETATM records.
    :type sanitize_rebuild: Optional[bool]

    :param sanitize_aggressive:
        Whether sanitization should use aggressive cleanup heuristics.
    :type sanitize_aggressive: bool

    :param sanitize_backup:
        Whether a backup should be created before in-place sanitization.
    :type sanitize_backup: bool

    :returns:
        Produced PDBQT path.
    :rtype: Path
    """
    input_pdb = _ensure_exists(input_pdb, "Input PDB")
    output_pdbqt = Path(output_pdbqt).resolve()
    output_pdbqt.parent.mkdir(parents=True, exist_ok=True)

    if mode == "receptor":
        exe = _require_executable(meeko_cmd or "mk_prepare_receptor.py")
        args = [
            exe,
            "--read_pdb",
            str(input_pdb),
            "--write_pdbqt",
            str(output_pdbqt),
        ]
    else:
        exe = _require_executable(meeko_cmd or "mk_prepare_ligand.py")
        args = [exe, "-i", str(input_pdb), "-o", str(output_pdbqt)]

    args += list(extra_args or [])
    _run(args)

    if not output_pdbqt.exists():
        raise FileNotFoundError(f"PDBQT not produced: {output_pdbqt}")

    _sanitize_pdbqt(
        output_pdbqt,
        backend="meeko",
        rebuild=sanitize_rebuild,
        aggressive=sanitize_aggressive,
        backup=sanitize_backup,
    )
    return output_pdbqt


