def _sanitize_pdbqt(
    pdbqt_path: Path,
    *,
    backend: SanitizeBackend,
    rebuild: Optional[bool] = None,
    aggressive: bool = False,
    backup: bool = False,
) -> None:
    """
    Sanitize a produced PDBQT file unconditionally.

    Default rebuild policy depends on the backend:

    - ``"meeko"``  -> ``rebuild=True``
    - ``"obabel"`` -> ``rebuild=False``

    :param pdbqt_path:
        Path to the PDBQT file to sanitize.
    :type pdbqt_path: Path

    :param backend:
        Backend that produced the PDBQT file.
    :type backend: Literal["meeko", "obabel"]

    :param rebuild:
        Whether to rebuild ATOM/HETATM lines into fixed-width PDBQT layout. If
        ``None``, a backend-specific default is used.
    :type rebuild: Optional[bool]

    :param aggressive:
        Whether to enable more aggressive sanitization heuristics.
    :type aggressive: bool

    :param backup:
        Whether to create a backup file before overwriting in place.
    :type backup: bool

    :returns:
        This function returns nothing.
    :rtype: None

    :raises FileNotFoundError:
        If the requested PDBQT file does not exist.
    """
    pdbqt_path = Path(pdbqt_path)
    if not pdbqt_path.exists():
        raise FileNotFoundError(f"PDBQT file does not exist: {pdbqt_path}")

    if rebuild is None:
        rebuild = True if backend == "meeko" else False

    logger.info(
        "Sanitizing %s-produced PDBQT: %s (rebuild=%s, aggressive=%s)",
        backend,
        pdbqt_path,
        rebuild,
        aggressive,
    )
    PDBQTSanitizer.sanitize_file(
        pdbqt_path,
        out_path=None,
        backend=backend,
        rebuild=rebuild,
        aggressive=aggressive,
        backup=backup,
    )


def _contains_atom_records(text: str) -> bool:
    """
    Check whether a text block contains PDB-style atom records.

    :param text:
        File contents to inspect.
    :type text: str

    :returns:
        ``True`` if at least one ``ATOM`` or ``HETATM`` record is present.
    :rtype: bool
    """
    return any(
        line.startswith("ATOM") or line.startswith("HETATM")
        for line in text.splitlines()
    )


def _validate_receptor_pdbqt(
    pdbqt_path: Path,
    *,
    flexible: bool = False,
) -> None:
    """
    Validate that a produced PDBQT matches the requested receptor mode.

    When ``flexible=False``, the file must not contain ligand-style torsion-tree
    markers. When ``flexible=True``, torsion-tree markers are allowed.

    :param pdbqt_path:
        Path to the PDBQT file to validate.
    :type pdbqt_path: Path

    :param flexible:
        Whether the receptor is expected to be flexible.
    :type flexible: bool

    :returns:
        This function returns nothing.
    :rtype: None

    :raises RuntimeError:
        If the file is malformed or inconsistent with the requested receptor
        mode.
    """
    text = Path(pdbqt_path).read_text(encoding="utf-8", errors="replace")

    if not _contains_atom_records(text):
        raise RuntimeError(
            f"Invalid receptor PDBQT: no ATOM/HETATM lines in {pdbqt_path}"
        )

    if not flexible:
        forbidden = (
            "ROOT",
            "BRANCH",
            "ENDBRANCH",
            "ENDROOT",
            "TORSDOF",
            "active torsions",
        )
        text_lower = text.lower()
        for token in forbidden:
            if token.lower() in text_lower:
                raise RuntimeError(
                    f"Invalid rigid receptor PDBQT: found forbidden token '{token}' "
                    f"in {pdbqt_path}. Open Babel likely wrote a flexible PDBQT."
                )


