def pdb_to_pdbqt(
    input_pdb: Union[str, Path],
    output_pdbqt: Union[str, Path],
    *,
    mode: Mode,
    backend: Backend,
    extra_args: Optional[Sequence[str]] = None,
    meeko_cmd: Optional[str] = None,
    mgltools_cmd: Optional[str] = None,
    sanitize_rebuild: Optional[bool] = None,
    sanitize_aggressive: bool = False,
    sanitize_backup: bool = False,
    validate_receptor: Optional[bool] = None,
    flexibility: bool = False,
) -> Path:
    """
    Convert PDB to PDBQT using a single explicit backend.
    """
    input_pdb = _ensure_exists(input_pdb, "Input PDB")
    output_pdbqt = Path(output_pdbqt).resolve()
    output_pdbqt.parent.mkdir(parents=True, exist_ok=True)

    if validate_receptor is None:
        validate_receptor = mode == "receptor"

    if backend == "meeko":
        return _meeko_pdb_to_pdbqt(
            input_pdb,
            output_pdbqt,
            mode=mode,
            extra_args=extra_args,
            meeko_cmd=meeko_cmd,
            sanitize_rebuild=sanitize_rebuild,
            sanitize_aggressive=sanitize_aggressive,
            sanitize_backup=sanitize_backup,
        )

    if backend == "obabel":
        convert_with_obabel(
            input_pdb,
            output_pdbqt,
            extra_args=_default_obabel_pdbqt_args(extra_args),
            sanitize_rebuild=sanitize_rebuild,
            sanitize_aggressive=sanitize_aggressive,
            sanitize_backup=sanitize_backup,
            validate_receptor=validate_receptor,
            flexibility=flexibility,
        )
        return output_pdbqt

    if backend == "mgltools":
        return _mgltools_pdb_to_pdbqt(
            input_pdb,
            output_pdbqt,
            mode=mode,
            extra_args=extra_args,
            mgltools_cmd=mgltools_cmd,
        )

    raise ValueError("backend must be one of: 'meeko', 'obabel', 'mgltools'.")


def pdbqt_to_pdb(
    input_pdbqt: Union[str, Path],
    output_pdb: Union[str, Path],
    *,
    backend: Literal["obabel"],
    extra_args: Optional[Sequence[str]] = None,
) -> Path:
    """
    Convert PDBQT to PDB using Open Babel.
    """
    if backend != "obabel":
        raise NotImplementedError(
            "PDBQT -> PDB is only supported with backend='obabel'."
        )

    input_pdbqt = _ensure_exists(input_pdbqt, "Input PDBQT")
    output_pdb = Path(output_pdb).resolve()
    output_pdb.parent.mkdir(parents=True, exist_ok=True)

    convert_with_obabel(
        input_pdbqt,
        output_pdb,
        extra_args=extra_args,
        validate_receptor=False,
    )

    if not output_pdb.exists():
        raise FileNotFoundError(f"PDB not produced: {output_pdb}")

    return output_pdb


def sdf_to_pdb(
    input_sdf: Union[str, Path],
    output_pdb: Union[str, Path],
    *,
    backend: Literal["rdkit", "obabel"],
    extra_args: Optional[Sequence[str]] = None,
) -> Path:
    """
    Convert SDF to PDB using a single explicit backend.
    """
    input_sdf = _ensure_exists(input_sdf, "Input SDF")
    output_pdb = Path(output_pdb).resolve()
    output_pdb.parent.mkdir(parents=True, exist_ok=True)

    if backend == "rdkit":
        _rdkit_require()
        suppl = Chem.SDMolSupplier(str(input_sdf), removeHs=False, sanitize=True)  # type: ignore[arg-type]
        mol = next((m for m in suppl if m is not None), None)
        if mol is None:
            raise ValueError(f"No valid molecule found in {input_sdf}")
        Chem.MolToPDBFile(mol, str(output_pdb))  # type: ignore[arg-type]

    elif backend == "obabel":
        convert_with_obabel(
            input_sdf,
            output_pdb,
            extra_args=extra_args,
            validate_receptor=False,
        )

    else:
        raise ValueError("backend must be 'rdkit' or 'obabel'.")

    if not output_pdb.exists():
        raise FileNotFoundError(f"PDB not produced: {output_pdb}")

    return output_pdb


