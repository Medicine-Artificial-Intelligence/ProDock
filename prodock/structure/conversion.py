def _ensure_exists(path: Union[str, Path], kind: str) -> Path:
    """
    Ensure that a path exists and return its resolved form.

    :param path:
        File path to validate.
    :type path: Union[str, Path]

    :param kind:
        Human-readable label used in error messages.
    :type kind: str

    :returns:
        Resolved existing path.
    :rtype: Path

    :raises FileNotFoundError:
        If the path does not exist.
    """
    p = Path(path).resolve()
    if not p.exists():
        raise FileNotFoundError(f"{kind} not found: {p}")
    return p


def _resolve_executable(command: str) -> Optional[str]:
    """
    Resolve an executable name or explicit path.

    :param command:
        Executable name or filesystem path.
    :type command: str

    :returns:
        Absolute executable path if found, otherwise ``None``.
    :rtype: Optional[str]
    """
    candidate = Path(command)
    if candidate.exists():
        return str(candidate.resolve())
    return shutil.which(command)


def _require_executable(command: str) -> str:
    """
    Require that an executable exists.

    :param command:
        Executable name or explicit path.
    :type command: str

    :returns:
        Resolved executable path.
    :rtype: str

    :raises RuntimeError:
        If the executable cannot be found.
    """
    exe = _resolve_executable(command)
    if exe is None:
        raise RuntimeError(f"Required executable not found: {command}")
    return exe


def _run(args: Sequence[str]) -> subprocess.CompletedProcess:
    """
    Run a subprocess command and raise on failure.

    :param args:
        Command-line argument vector.
    :type args: Sequence[str]

    :returns:
        Completed subprocess result.
    :rtype: subprocess.CompletedProcess

    :raises RuntimeError:
        If the command exits with a non-zero return code.
    """
    proc = subprocess.run(
        list(args),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"Command failed (rc={proc.returncode}): {' '.join(map(str, args))}\n"
            f"STDOUT:\n{proc.stdout}\n"
            f"STDERR:\n{proc.stderr}"
        )
    return proc


