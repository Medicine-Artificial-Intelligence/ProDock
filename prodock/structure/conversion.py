def ensure_pdbqt(
    input_path: Union[str, Path],
    output_dir: Union[str, Path],
    *,
    backend: Backend,
    mode: Mode = "ligand",
    tmp_from_sdf_backend: TmpConv = "rdkit",
    extra_args: Optional[Sequence[str]] = None,
    meeko_cmd: Optional[str] = None,
    mgltools_cmd: Optional[str] = None,
    sanitize_rebuild: Optional[bool] = None,
    sanitize_aggressive: bool = False,
    sanitize_backup: bool = False,
    validate_receptor: Optional[bool] = None,
    flexibility: bool = False,
) -> Path:
    """
    Ensure that an input file is available as PDBQT using the chosen backend.
    """
    _ = tmp_from_sdf_backend
    p = _ensure_exists(input_path, "Input")
    out_dir = Path(output_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    ext = p.suffix.lower()
    out_p = out_dir / f"{p.stem}.pdbqt"

    if ext == ".pdbqt":
        return p

    if ext == ".pdb":
        return pdb_to_pdbqt(
            p,
            out_p,
            mode=mode,
            backend=backend,
            extra_args=extra_args,
            meeko_cmd=meeko_cmd,
            mgltools_cmd=mgltools_cmd,
            sanitize_rebuild=sanitize_rebuild,
            sanitize_aggressive=sanitize_aggressive,
            sanitize_backup=sanitize_backup,
            validate_receptor=validate_receptor,
            flexibility=flexibility,
        )

    if ext == ".sdf":
        return sdf_to_pdbqt(
            p,
            out_p,
            backend=backend,
            tmp_from_sdf_backend=tmp_from_sdf_backend,
            extra_args=extra_args,
            meeko_cmd=meeko_cmd,
            mgltools_cmd=mgltools_cmd,
            sanitize_rebuild=sanitize_rebuild,
            sanitize_aggressive=sanitize_aggressive,
            sanitize_backup=sanitize_backup,
        )

    if ext in {".mol2", ".smi"}:
        if backend != "obabel":
            raise NotImplementedError(
                f"Input extension {ext} to PDBQT is only supported with backend='obabel'."
            )

        convert_with_obabel(
            p,
            out_p,
            extra_args=_default_obabel_pdbqt_args(extra_args),
            sanitize_rebuild=sanitize_rebuild,
            sanitize_aggressive=sanitize_aggressive,
            sanitize_backup=sanitize_backup,
            validate_receptor=(
                (mode == "receptor") if validate_receptor is None else validate_receptor
            ),
            flexibility=flexibility,
        )

        if not out_p.exists():
            raise FileNotFoundError(f"PDBQT not produced: {out_p}")
        return out_p

    raise NotImplementedError(
        f"Unsupported input extension {ext} for ensure_pdbqt with backend='{backend}'."
    )


def pdb_to_sdf(
    input_pdb: Union[str, Path],
    output_sdf: Union[str, Path],
    *,
    backend: Literal["rdkit", "obabel"],
    extra_args: Optional[Sequence[str]] = None,
) -> Path:
    """
    Convert PDB to SDF using a single explicit backend.
    """
    input_pdb = _ensure_exists(input_pdb, "Input PDB")
    output_sdf = Path(output_sdf).resolve()
    output_sdf.parent.mkdir(parents=True, exist_ok=True)

    if backend == "rdkit":
        _rdkit_require()
        mol = Chem.MolFromPDBFile(str(input_pdb), removeHs=False)  # type: ignore[arg-type]
        if mol is None:
            raise ValueError(f"RDKit could not parse PDB: {input_pdb}")
        writer = Chem.SDWriter(str(output_sdf))  # type: ignore[arg-type]
        writer.write(mol)
        writer.close()

    elif backend == "obabel":
        convert_with_obabel(
            input_pdb,
            output_sdf,
            extra_args=extra_args,
            validate_receptor=False,
        )

    else:
        raise ValueError("backend must be 'rdkit' or 'obabel'.")

    if not output_sdf.exists():
        raise FileNotFoundError(f"SDF not produced: {output_sdf}")

    return output_sdf


def pdbqt_to_sdf(
    input_pdbqt: Union[str, Path],
    output_sdf: Union[str, Path],
    *,
    backend: PDBQTToSDFBackend = "auto",
    extra_args: Optional[Sequence[str]] = None,
    is_dlg: bool = False,
    sanitize: bool = True,
) -> Path:
    """
    Convert PDBQT to SDF.
    """
    input_pdbqt = _ensure_exists(input_pdbqt, "Input PDBQT")
    output_sdf = Path(output_sdf).resolve()
    output_sdf.parent.mkdir(parents=True, exist_ok=True)

    text = _read_text(input_pdbqt)
    has_metadata = _has_meeko_metadata(text)

    if backend == "auto":
        if has_metadata:
            return _meeko_pdbqt_to_sdf(
                input_pdbqt,
                output_sdf,
                is_dlg=is_dlg,
                sanitize=sanitize,
            )
        convert_with_obabel(
            input_pdbqt,
            output_sdf,
            extra_args=extra_args,
            validate_receptor=False,
        )

    elif backend == "meeko":
        return _meeko_pdbqt_to_sdf(
            input_pdbqt,
            output_sdf,
            is_dlg=is_dlg,
            sanitize=sanitize,
        )

    elif backend == "obabel":
        convert_with_obabel(
            input_pdbqt,
            output_sdf,
            extra_args=extra_args,
            validate_receptor=False,
        )

    else:
        raise ValueError("backend must be one of: 'auto', 'meeko', 'obabel'.")

    if not output_sdf.exists():
        raise FileNotFoundError(f"SDF not produced: {output_sdf}")

    return output_sdf


