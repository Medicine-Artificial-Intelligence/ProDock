    output_pdbqt = Path(output_pdbqt).resolve()
    output_pdbqt.parent.mkdir(parents=True, exist_ok=True)

    exe = _require_executable(mgltools_cmd or "prepare_ligand4.py")
    args = [exe, "-l", str(input_sdf), "-o", str(output_pdbqt)]
    args += list(extra_args or [])
    _run(args)

    if not output_pdbqt.exists():
        raise FileNotFoundError(f"PDBQT not produced: {output_pdbqt}")

    logger.info(
        "MGLTools produced PDBQT without sanitizer pass: %s",
        output_pdbqt,
    )
    return output_pdbqt


