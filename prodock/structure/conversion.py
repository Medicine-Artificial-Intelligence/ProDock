"""
Conversion helpers for Meeko, Open Babel, RDKit, and MGLTools.

This module provides two API layers:

1. Backend-specific conversion helpers
   - :func:`convert_with_mekoo`
   - :func:`convert_with_meeko`
   - :func:`convert_with_obabel`

2. Higher-level format conversion helpers
   - :func:`pdb_to_pdbqt`
   - :func:`pdbqt_to_pdb`
   - :func:`sdf_to_pdb`
   - :func:`sdf_to_pdbqt`
   - :func:`ensure_pdbqt`
   - :func:`pdb_to_sdf`
   - :func:`pdbqt_to_sdf`

Design notes
~~~~~~~~~~~~
- PDBQT files generated by Meeko or Open Babel are sanitized unconditionally.
- Receptor validation is available for Open Babel PDBQT receptor generation.
- MGLTools output is supported, but not sanitized here because the sanitizer is
  backend-aware for ``"meeko"`` and ``"obabel"`` only.
- The public name :func:`convert_with_mekoo` is preserved for backward
  compatibility. :func:`convert_with_meeko` is provided as an alias.
"""

